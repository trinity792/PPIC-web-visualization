/**
 * Server-side geography (geometry) access module.
 *
 * Mirrors the other lib/data/* modules: it owns reading, parsing, and caching of
 * the cleaned GeoJSON used by choropleth maps. The API route is a thin
 * orchestrator on top of it; client components fetch the route, never the file.
 *
 * The geometry lives under data/data-cleaned/ (not public/), so it is NOT served
 * as a static asset — this server module + /api/geography are how the browser
 * reaches it.
 *
 * NOTE: server-only (uses node:fs) — must not be imported into a "use client"
 * component.
 *
 * Every feature carries `properties.GEOID` (its canonical id) and
 * `properties.NAME`. A choropleth should join on GEOID where possible (guardrail
 * #5: join on canonical ids, not display names); NAME matches the dataset's
 * `Location` values for the simple case.
 *   - counties: GEOID is the FIPS id, e.g. "06001"; NAME is e.g. "Alameda".
 *   - regions: these have no official code, so GEOID is the project's canonical
 *     region name, the same as NAME, e.g. "Bay Area".
 *   - states: GEOID is the FIPS id, e.g. "02"; NAME is e.g. "Alaska"; STUSPS is
 *     e.g. "AK", because datasets label states either way. Alaska, Hawaii, and
 *     Puerto Rico are relocated near the lower 48, so these coordinates are for
 *     display only.
 *   - metros: GEOID is the CBSA code, e.g. "40140"; NAME is the short label the
 *     datasets use, e.g. "Riverside"; ALT_NAME is a second label where datasets
 *     differ, e.g. "Inland Empire" (Building Permits), or null. 26 California
 *     metros on the older delineation, with Fresno and Madera split along the
 *     county line (scripts/shared/geography/extract_california_metros.py).
 *
 * All four files are generated by scripts/shared/geography/simplify_geometries.py.
 * Their outer rings run clockwise, the reverse of the GeoJSON standard, because
 * Plotly's d3-geo drawing reads a standard ring as filling everything outside it.
 */

/* global process */

import { readFile } from "node:fs/promises";
import path from "node:path";

import { representativePoint } from "@/lib/geography/representativePoint";

// Cleaned GeoJSON paths, scoped under process.cwd()/data/data-cleaned/geography
// (its own leaf folder, like the sibling datasets). A new level is a new
// statically-known const + switch arm.
const COUNTIES_GEOJSON = path.join(
  process.cwd(),
  "data",
  "data-cleaned",
  "geography",
  "california-counties.geojson",
);
const REGIONS_GEOJSON = path.join(
  process.cwd(),
  "data",
  "data-cleaned",
  "geography",
  "california-regions.geojson",
);
const STATES_GEOJSON = path.join(
  process.cwd(),
  "data",
  "data-cleaned",
  "geography",
  "us-states.geojson",
);
const METROS_GEOJSON = path.join(
  process.cwd(),
  "data",
  "data-cleaned",
  "geography",
  "california-metros.geojson",
);

/** Geographic levels with available geometry. */
export const AVAILABLE_GEO_LEVELS = ["counties", "regions", "states", "metros"];

/** Property key holding the canonical id, by level — the choropleth featureidkey. */
export const FEATURE_ID_KEYS = Object.freeze({
  counties: "properties.GEOID",
  regions: "properties.GEOID",
  states: "properties.GEOID",
  metros: "properties.GEOID",
});

// Parsed-geometry cache so each GeoJSON is read and parsed once per server process.
const cache = new Map();

/**
 * Read the raw GeoJSON for a level. Each arm passes a statically-known path to
 * readFile so the bundler can scope file tracing (a dynamic path lookup makes
 * Turbopack trace the whole project).
 */
function readGeojsonText(level) {
  switch (level) {
    case "counties":
      return readFile(COUNTIES_GEOJSON, "utf8");
    case "regions":
      return readFile(REGIONS_GEOJSON, "utf8");
    case "states":
      return readFile(STATES_GEOJSON, "utf8");
    case "metros":
      return readFile(METROS_GEOJSON, "utf8");
    default:
      return null;
  }
}

/**
 * Load and cache the GeoJSON FeatureCollection for a geographic level.
 * @param {string} level e.g. "counties"
 * @returns {Promise<object>} a GeoJSON FeatureCollection
 */
export async function loadGeometry(level) {
  if (!AVAILABLE_GEO_LEVELS.includes(level)) {
    throw new Error(`Unknown geographic level: ${level}`);
  }
  if (cache.has(level)) return cache.get(level);

  let text;
  try {
    text = await readGeojsonText(level);
  } catch (error) {
    if (error.code === "ENOENT") {
      throw new Error(
        `Geometry for "${level}" not found. Add the cleaned GeoJSON to generate it.`,
      );
    }
    throw error;
  }

  const geojson = JSON.parse(text);
  cache.set(level, geojson);
  return geojson;
}

/**
 * Build a display-name → canonical feature-id lookup for joining cleaned data
 * rows to geometry. The returned ids match FEATURE_ID_KEYS for the level. State
 * datasets label places as either "Alaska" or "AK", and metro datasets as either
 * "Riverside" or "Inland Empire", so both resolve.
 */
export async function getFeatureIdLookup(level) {
  const geojson = await loadGeometry(level);
  const lookup = new Map();
  for (const feature of geojson.features || []) {
    const { NAME: name, STUSPS: abbreviation, ALT_NAME: alternate, GEOID: id } = feature.properties || {};
    if (!id) continue;
    if (name) lookup.set(name, id);
    if (abbreviation) lookup.set(abbreviation, id);
    if (alternate) lookup.set(alternate, id);
  }
  return lookup;
}

// Derived-point cache, parallel to `cache` above: each level's points are
// computed from its polygons once per server process.
const pointCache = new Map();

/**
 * A representative [lon, lat] point per feature at a level, keyed by GEOID —
 * what a symbol map plots. Derived from the same polygons a choropleth
 * draws (see lib/geography/representativePoint.js); there is no separate,
 * authoritative point source for any level today.
 * @param {string} level e.g. "counties"
 * @returns {Promise<Record<string, [number, number]>>}
 */
export async function loadRepresentativePoints(level) {
  if (pointCache.has(level)) return pointCache.get(level);

  const geojson = await loadGeometry(level);
  const points = {};
  for (const feature of geojson.features || []) {
    const id = feature.properties?.GEOID;
    if (id) points[id] = representativePoint(feature.geometry);
  }
  pointCache.set(level, points);
  return points;
}
